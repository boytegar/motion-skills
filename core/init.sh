#!/usr/bin/env bash
# motion init – interactive setup: pick a default style, persist to config.
#
#   ./core/init.sh
#   $MOTION_LIB/core/init.sh
#
# Writes MOTION_STYLE into
#   ~/.config/motion-explainer/config.env   (via motion_config_set from env.sh)
#
# Then generates two reference documents in the series folder (or $PWD):
#   design.md   – the chosen style's visual DNA, palette, doc paths
#   agents.md   – agent defaults: style, canvas, skill call reference
#
# Options:
#   --series DIR   generate design.md / agents.md in DIR instead of $PWD
#   --yes, -y      use the first style without prompting (CI/non-interactive)
#   --dry-run      print what would happen, change nothing
set -euo pipefail

L="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$L/env.sh"

SERIES="${PWD}"; YES=0; DRY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --series) SERIES="${2:?--series needs a directory}"; shift 2 ;;
    --yes|-y) YES=1; shift ;;
    --dry-run) DRY=1; shift ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) echo "unknown option: $1 (see --help)" >&2; exit 2 ;;
  esac
done

[ -t 1 ] && { B=$'\033[1m'; G=$'\033[32m'; Y=$'\033[33m'; C=$'\033[36m'; N=$'\033[0m'; } || { B=""; G=""; Y=""; C=""; N=""; }
say()  { printf '%s==>%s %s\n' "$B" "$N" "$*"; }
ok()   { printf '  %s[ok]%s %s\n' "$G" "$N" "$*"; }
info() { printf '  %s...%s %s\n' "$C" "$N" "$*"; }
run()  { [ "$DRY" = 1 ] && printf '  (dry-run) %s\n' "$*" || "$@"; }
ask()  { [ "$YES" = 1 ] && return 0; printf '%s ' "$1"; read -r REPLY; }

# ------------------------------------------------------------------ style
say "motion init"
echo

STYLES=(); while IFS= read -r s; do STYLES+=("$s"); done < <(motion_styles)
if [ "${#STYLES[@]}" -eq 0 ]; then
  echo "no styles found under $MOTION_STYLES" >&2; exit 2
fi

STYLE_CHOICE="${MOTION_STYLE:-}"

if [ -z "$STYLE_CHOICE" ] || [ "$YES" = 0 ]; then
  echo "${B}Available styles:${N}"
  idx=1
  for s in "${STYLES[@]}"; do
    tl="$(python3 -c "import json,sys; print(json.load(open(sys.argv[1])).get('tagline','')[:84])" "$MOTION_STYLES/$s/style.json" 2>/dev/null || echo "")"
    printf '  %2d) %-22s %s\n' "$idx" "$s" "$tl"
    idx=$((idx+1))
  done
  echo
  if [ "$YES" = 1 ]; then
    STYLE_CHOICE="${STYLES[0]}"
    printf '  auto-selected: %s\n' "$STYLE_CHOICE"
  else
    default_idx=1
    for i in "${!STYLES[@]}"; do [ "${STYLES[$i]}" = "${MOTION_STYLE:-}" ] && default_idx=$((i+1)) && break; done
    printf 'Choose style [%d]: ' "$default_idx"
    read -r c
    c="${c:-$default_idx}"
    if [[ "$c" =~ ^[0-9]+$ ]] && [ "$c" -ge 1 ] && [ "$c" -le "${#STYLES[@]}" ]; then
      STYLE_CHOICE="${STYLES[$((c-1))]}"
    else
      echo "invalid choice: $c" >&2; exit 2
    fi
  fi
fi

STYLE_JSON="$MOTION_STYLES/$STYLE_CHOICE/style.json"
[ -f "$STYLE_JSON" ] || { echo "unknown style '$STYLE_CHOICE'" >&2; exit 2; }

# ------------------------------------------------------------------ persist
echo
say "Saving defaults"
run motion_config_set MOTION_STYLE "$STYLE_CHOICE"
[ "$DRY" = 1 ] || MOTION_STYLE="$STYLE_CHOICE"
ok "MOTION_STYLE=$STYLE_CHOICE  → $_pc_cfg"

# ------------------------------------------------------------------ design.md
SERIES="$(cd "$SERIES" && pwd)"
DESIGN_MD="$SERIES/design.md"

STYLE_TITLE="$(python3 -c "import json,sys; print(json.load(open(sys.argv[1])).get('title','$STYLE_CHOICE'))" "$STYLE_JSON")"
STYLE_TAGLINE="$(python3 -c "import json,sys; print(json.load(open(sys.argv[1])).get('tagline',''))" "$STYLE_JSON")"
STYLE_DESC="$(python3 -c "import json,sys; print(json.load(open(sys.argv[1])).get('description',''))" "$STYLE_JSON")"
CANVAS="$(python3 -c "import json,sys; c=json.load(open(sys.argv[1])).get('canvas') or {}; w=c.get('width'); print('%sx%s, %s fps' % (w, c.get('height'), c.get('fps')) if w else 'not declared in style.json (see the style guide)')" "$STYLE_JSON")"

GUIDE_REL="$MOTION_STYLES/$STYLE_CHOICE/docs/style-guide.md"
PROMPT_REL="$MOTION_STYLES/$STYLE_CHOICE/docs/style-prompt.md"

say "Generating design.md"
run cat > "$DESIGN_MD" <<DESIGN_EOF
# Design Reference — ${STYLE_TITLE}

> ${STYLE_TAGLINE}

**Style:** \`${STYLE_CHOICE}\`
**Canvas:** ${CANVAS}

${STYLE_DESC}

## Style DNA

See the full style guide:
\`\`\`
${GUIDE_REL}
\`\`\`

Portable prompt blocks for other tools:
\`\`\`
${PROMPT_REL}
\`\`\`

## Palette (${STYLE_CHOICE})

$(python3 - "$GUIDE_REL" 2>/dev/null <<'PYEOF'
import sys, re
path = sys.argv[1]
try:
    text = open(path).read()
    palettes = re.findall(r'(?i)(palette.*?)\n(?=##|\Z)', text, re.S)
    if palettes:
        print(palettes[0][:600].strip())
    else:
        print("See style-guide.md for the full palette.")
except Exception:
    print("See style-guide.md for the full palette.")
PYEOF
)

## Motion & timing

See \`${GUIDE_REL}\` sections on camera, boil, and motion timings.

---
*Generated by \`core/init.sh\` on $(date '+%Y-%m-%d'). Re-run \`$MOTION_LIB/core/init.sh --series $SERIES\` to refresh.*
DESIGN_EOF

ok "design.md → $DESIGN_MD"

# ------------------------------------------------------------------ agents.md
AGENTS_MD="$SERIES/agents.md"

say "Generating agents.md"
run cat > "$AGENTS_MD" <<AGENTS_EOF
# Agent Defaults — ${STYLE_TITLE}

This file is the single source of truth for agents operating in this series.
Agents read it at the start of each session and do **not** ask the user for the style.

## Defaults

| Key | Value |
|-----|-------|
| \`MOTION_STYLE\` | \`${STYLE_CHOICE}\` |
| Canvas | ${CANVAS} |

> \`MOTION_STYLE\` is also persisted to \`${_pc_cfg}\` and exported by \`core/env.sh\`.

## Style — ${STYLE_CHOICE}

| Reference | Path |
|-----------|------|
| Style guide (DNA) | \`${GUIDE_REL}\` |
| Portable prompt | \`${PROMPT_REL}\` |
| Design reference | \`${DESIGN_MD}\` |

## Scope

This series is **plan-only**. The planning skills write the brief, hook, script, storyboard,
voice timing and the handoff contract, then stop. No scene code is written here and nothing is
rendered: building the plan folder belongs to whatever the user builds with, recorded in
\`video/HANDOFF.md\`.

## Workflow quick-reference for agents

Agents use these skills in order. No need to pass the style — they read this file.

| Stage | Skill | Writes |
|-------|-------|--------|
| Strategy & brief | \`motion-strategy\` | \`SERIES.md\` (step 0), \`research/facts.md\`, episode folder |
| Hook | \`motion-hook\` | \`video/STORYBOARD.md\` HOOK block |
| Script | \`motion-script\` | \`narration/script.json\`, staging table |
| Storyboard | \`motion-storyboard\` | camera/cut table, scene blocks, SFX plan |
| Voice & timing | \`motion-voice\` | \`narration/\`, \`public/vo/captions.json\`, \`src/plan.json\` |
| Plan & handoff | \`motion-build\` | \`episode.json\`, \`tools/cues.json\`, \`HANDOFF.md\` |
| QA (after a render) | \`motion-qa\` | fixes, delivery summary |

## Calling skills

When an agent invokes a planning skill it passes no style flag. The style resolves from
\`MOTION_STYLE\` (set via \`core/env.sh\`) and from \`video/episode.json\` \`"style"\`.

---
*Generated by \`core/init.sh\` on $(date '+%Y-%m-%d'). Re-run \`$MOTION_LIB/core/init.sh --series $SERIES\` to refresh.*
AGENTS_EOF

ok "agents.md → $AGENTS_MD"

# ------------------------------------------------------------------ done
echo
say "Done"
printf '  style   %s%s%s\n' "$C" "$STYLE_CHOICE" "$N"
printf '  config  %s\n' "$_pc_cfg"
printf '  design  %s\n' "$DESIGN_MD"
printf '  agents  %s\n' "$AGENTS_MD"
echo
printf 'Next: run motion-strategy in your coding agent, or the next planning skill in the chain.\n'
