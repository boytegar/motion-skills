#!/usr/bin/env python3
"""Generate multi-file scene stubs from episode.json for both Remotion and fframes."""
import json
import os
import re
import sys

def snake_case(name: str) -> str:
    s = re.sub('(.)([A-Z][a-z]+)', r'\1_\2', name)
    return re.sub('([a-z0-9])([A-Z])', r'\1_\2', s).lower()

def run():
    if not os.path.exists("episode.json"):
        sys.exit("error: episode.json not found in current directory")

    ep = json.load(open("episode.json"))
    engine = ep.get("engine", "remotion")
    scenes = [s[0] for s in ep.get("scenes", [])]
    banners = ep.get("banners", {})

    if not scenes:
        sys.exit("error: no scenes found in episode.json")

    os.makedirs("src/scenes", exist_ok=True)

    if engine == "fframes":
        # Multi-file Rust: src/scenes/mod.rs + src/scenes/<scene_snake>.rs
        mod_lines = ["// Generated by stubs.py from episode.json - do not edit manually"]
        for s in scenes:
            mod_name = snake_case(s)
            mod_lines.append(f"pub mod {mod_name};")
            mod_lines.append(f"pub use {mod_name}::*;")

        with open("src/scenes/mod.rs", "w") as f:
            f.write("\n".join(mod_lines) + "\n")

        made = 0
        for s in scenes:
            mod_name = snake_case(s)
            p = f"src/scenes/{mod_name}.rs"
            if os.path.exists(p):
                continue
            banner = banners.get(s, "")
            with open(p, "w") as f:
                f.write(f"""// {s}: STUB, replaced by scene agent (see STORYBOARD.md).
// Banner: "{banner}"
use fframes::{{Duration, Frame, FFramesContext, Scene, Svgr, Color}};

pub struct {s};

impl Scene for {s} {{
    fn duration(&self) -> Duration<'_> {{
        Duration::Seconds(2.0)
    }}

    fn render<'a>(&'a self, _frame: Frame, _ctx: &FFramesContext<'a, '_>) -> Svgr<'a> {{
        Svgr::Empty
    }}
}}
""")
            made += 1
        print(f"[fframes] {len(scenes)} scenes in src/scenes/mod.rs, {made} new stubs generated.")

    else:
        # Multi-file TSX: src/scenes/index.ts + src/scenes/<Scene>.tsx
        imp = "\n".join(f"import {{{i}}} from './{i}';" for i in scenes)
        rows = "\n".join(f"  {{id: '{i}', component: {i}, banner: {json.dumps(banners.get(i, ''), ensure_ascii=False)}, band: 0.745}}," for i in scenes)

        with open("src/scenes/index.ts", "w") as f:
            f.write(f"""// Scene registry (generated by stubs.py from episode.json): id -> component, banner, band.
import React from 'react';
{imp}

export type SceneDef = {{id: string; component: React.FC; banner: string; band: number}};
export const SCENES: SceneDef[] = [
{rows}
];
""")

        made = 0
        for s in scenes:
            p = f"src/scenes/{s}.tsx"
            if os.path.exists(p):
                continue
            with open(p, "w") as f:
                f.write(f"""// {s}: STUB, replaced by its scene agent (see STORYBOARD.md).
import React from 'react';
import {{AbsoluteFill}} from 'remotion';

export const {s}: React.FC = () => (
  <AbsoluteFill>
    <div style={{{{width: '100%', height: '100%', backgroundColor: '#222'}}}} />
  </AbsoluteFill>
);
""")
            made += 1
        print(f"[remotion] {len(scenes)} scenes in src/scenes/index.ts, {made} new stubs generated.")

if __name__ == "__main__":
    run()
