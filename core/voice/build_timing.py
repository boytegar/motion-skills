# Build timing.js: per-line duration + word timestamps aligned to the script text.
# Word times, best first:
#   1. a pace file from tools/pace.py, which rates the audio's own energy envelope, so a slow or paused
#      delivery drags the captions with it (no ASR needed)
#   2. ASR json (from voice/asr.py), words matched to the script with the gaps interpolated
#   3. a 2.75 wps estimate, only when there is no audio to read
#   env: PACE=<pace json> (default voice/pace_<ROLE>.json), CHOSEN, TIMING_OUT, ROLE
import json, sys, re, difflib, os, wave


def wavdur(path):
    try:
        with wave.open(path) as w:
            return w.getnframes() / w.getframerate()
    except (OSError, wave.Error):
        return 0.0


ROLE = os.environ.get("ROLE", "narrator")
script = json.load(open("script.json"))
asr = json.load(open(sys.argv[1])) if len(sys.argv) > 1 and os.path.exists(sys.argv[1]) else {}
CH = os.environ.get("CHOSEN", "voice/chosen.json")
chosen = json.load(open(CH)) if os.path.exists(CH) else {}
PP = os.environ.get("PACE", f"voice/pace_{ROLE}.json")
pace = json.load(open(PP)) if os.path.exists(PP) else {}
norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower())
seg = {}
for ln in script:
    words = ln["text"].split()
    path = chosen.get(ln["id"])
    p = (pace.get(path) or pace.get(ln["id"])) if pace else None
    a = asr.get(path) if path else None
    if p and p.get("words"):
        times = [(s, e) for s, e in p["words"]]
        dur = p.get("dur") or wavdur(path) or (times[-1][1] if times else 0.0)
        if len(times) != len(words):            # the transcript differs from the script: spread the curve
            lo = times[0][0] if times else 0.0
            hi = times[-1][1] if times else dur
            span = max(1e-6, hi - lo)
            times = [(lo + span * i / len(words), lo + span * (i + 1) / len(words)) for i in range(len(words))]
    elif a:
        aw = a["words"]; dur = a["dur"]
        sm = difflib.SequenceMatcher(a=[norm(w) for w in words], b=[norm(x["w"]) for x in aw], autojunk=False)
        times = [None] * len(words)
        for blk in sm.get_matching_blocks():
            for k in range(blk.size): times[blk.a + k] = (aw[blk.b + k]["s"], aw[blk.b + k]["e"])
        # interpolate gaps between matched neighbours
        for i in range(len(words)):
            if times[i] is None:
                j = i
                while j < len(words) and times[j] is None: j += 1
                lo = times[i - 1][1] if i else 0.0
                hi = times[j][0] if j < len(words) else dur
                n = j - i
                for k in range(n): times[i + k] = (lo + (hi - lo) * k / n, lo + (hi - lo) * (k + 1) / n)
    else:
        # nothing measured the words: use the WAV's real length if we have one, and spread the words over it
        dur = (wavdur(path) if path else 0.0) or len(words) / 2.75 + 0.2
        times = [(i * dur / max(1, len(words)), (i + 1) * dur / max(1, len(words))) for i in range(len(words))]
    if path and not dur:
        dur = wavdur(path)
    seg[ln["id"]] = {"dur": round(dur, 3), "file": path, "words": [{"w": w, "s": round(t[0], 3), "e": round(t[1], 3)} for w, t in zip(words, times)]}
open(os.environ.get("TIMING_OUT", "timing.js"), "w").write("// generated by build_timing.py\nconst VO = " + json.dumps({"order": [l["id"] for l in script], "seg": seg}) + ";\n")
src = "pace" if pace else "asr" if asr else "estimate"
print(src, {k: v["dur"] for k, v in seg.items()}, "total", round(sum(v["dur"] for v in seg.values()), 1))
